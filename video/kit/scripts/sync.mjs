#!/usr/bin/env node
/*
 * kit/scripts/sync.mjs — vendor the kit into a film so the film renders on its own.
 *
 *   node kit/scripts/sync.mjs <film-dir | slug>      one film
 *   node kit/scripts/sync.mjs --all                  every film under video/films/
 *
 * Copies tokens.css, kit.css, lib/, blocks/, components/ into films/<slug>/kit/ (replacing what was
 * there: never edit a film's kit/ copy, edit video/kit/ and sync), writes the one-file bundle
 * films/<slug>/kit/kit.js (lib files in load order) and kit/VERSION, re-links node_modules, and
 * rewrites data/clips.js from data/clips/*.json.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const KIT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VIDEO = path.resolve(KIT, "..");
export const LIB_ORDER = ["core.js", "camera.js", "clips.js", "reveal.js", "captions.js", "scene.js", "cursor.js", "blocks.js"];

export function libFiles() {
  const all = fs.readdirSync(path.join(KIT, "lib")).filter((f) => f.endsWith(".js"));
  return LIB_ORDER.filter((f) => all.includes(f)).concat(all.filter((f) => !LIB_ORDER.includes(f)).sort());
}

function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name), d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

export function syncFilm(filmDir) {
  const film = path.resolve(filmDir);
  if (!fs.existsSync(path.join(film, "index.html"))) throw new Error("not a film (no index.html): " + film);
  const dst = path.join(film, "kit");
  fs.rmSync(dst, { recursive: true, force: true });
  fs.mkdirSync(dst, { recursive: true });
  for (const f of ["tokens.css", "kit.css"]) fs.copyFileSync(path.join(KIT, f), path.join(dst, f));
  for (const d of ["lib", "blocks", "components"]) copyDir(path.join(KIT, d), path.join(dst, d));
  const files = libFiles();
  const bundle = files.map((f) => `/* ---- kit/lib/${f} ---- */\n` + fs.readFileSync(path.join(KIT, "lib", f), "utf8")).join("\n");
  fs.writeFileSync(path.join(dst, "kit.js"), "/* kit.js: generated by kit/scripts/sync.mjs from video/kit/lib — do not edit here */\n" + bundle);
  const hash = crypto.createHash("sha1").update(bundle + fs.readFileSync(path.join(KIT, "kit.css"))).digest("hex").slice(0, 10);
  const version = (fs.readFileSync(path.join(KIT, "lib", "core.js"), "utf8").match(/Kit\.version = "([^"]+)"/) || [])[1] || "?";
  fs.writeFileSync(path.join(dst, "VERSION"), `kit ${version} ${hash} synced ${new Date().toISOString()}\nSource: video/kit (edit there, then: npm run sync -- ${path.basename(film)})\n`);
  // node_modules: share video/node_modules
  const nm = path.join(film, "node_modules");
  try {
    fs.lstatSync(nm);
  } catch {
    fs.symlinkSync(path.relative(film, path.join(VIDEO, "node_modules")), nm);
  }
  // data/clips.js
  const dataDir = path.join(film, "data", "clips");
  fs.mkdirSync(dataDir, { recursive: true });
  const all = {};
  fs.readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort().forEach((f) => {
    const c = JSON.parse(fs.readFileSync(path.join(dataDir, f), "utf8"));
    all[c.name] = c;
  });
  fs.writeFileSync(path.join(film, "data", "clips.js"), "/* generated by kit/scripts/build-footage.mjs from data/clips/*.json: do not edit */\nwindow.KIT_CLIPS = " + JSON.stringify(all) + ";\n");
  console.log(`synced kit ${version} (${hash}) -> ${path.relative(process.cwd(), dst) || dst}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const a = process.argv[2];
  if (!a) {
    console.error("usage: sync.mjs <film-dir | slug> | --all");
    process.exit(1);
  }
  const films = path.join(VIDEO, "films");
  const targets = a === "--all" ? fs.readdirSync(films).map((d) => path.join(films, d)).filter((d) => fs.existsSync(path.join(d, "index.html"))) : [fs.existsSync(a) ? a : path.join(films, a)];
  targets.forEach(syncFilm);
}
